"""把模型输出清洗成适合气泡显示的纯文本。

小模型经常不顾提示词输出 Markdown（反引号、代码块、标题、列表），
这些符号在气泡里显示很难看，因此在显示层做一道兜底清洗。

注意：这里不做字数截断——长回复由气泡分页轮播完整展示，
在这里砍掉的话用户就永远看不到全文了。
"""

import re


def clean(text: str) -> str:
    """去掉 Markdown 标记，保留可读内容。"""
    if not text:
        return ""

    s = text

    # 代码围栏：```lang ... ``` -> 保留里面的代码行（去掉围栏标记）
    s = re.sub(r"```[a-zA-Z0-9_+-]*\n?", "", s)
    s = s.replace("```", "")

    # 行内反引号
    s = s.replace("`", "")

    # 粗体/斜体
    s = s.replace("**", "").replace("__", "")

    # 标题符号、引用符号、列表符号（行首）
    s = re.sub(r"(?m)^\s{0,3}#{1,6}\s*", "", s)
    s = re.sub(r"(?m)^\s{0,3}>\s?", "", s)
    s = re.sub(r"(?m)^\s{0,3}[-*+]\s+", "· ", s)
    s = re.sub(r"(?m)^\s{0,3}\d+[.)]\s+", "", s)

    # 水平分割线
    s = re.sub(r"(?m)^\s*([-*_])\1{2,}\s*$", "", s)

    # 连续空行压成一行空行，去掉行尾空白
    s = re.sub(r"[ \t]+$", "", s, flags=re.M)
    s = re.sub(r"\n{3,}", "\n\n", s)
    return s.strip()
